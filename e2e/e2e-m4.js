const { chromium } = require('playwright');
require('./patch.js');
const { execSync } = require('child_process');
const SP = __dirname;
const B = 'http://localhost:3000';
const ok = (c, m) => { if (!c) { console.error('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
const sql = (q) => JSON.parse(execSync(`python3 ${SP}/q.py ` + JSON.stringify(q)).toString());
(async () => {
  const browser = await chromium.launch();
  const c = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' });
  const p = await c.newPage();
  const errors = []; p.on('pageerror', (e) => errors.push(e.message));
  await p.goto(B + '/login'); await p.click('text=건물주'); await p.click('button[type=submit]'); await p.waitForURL(B + '/customer');
  await p.goto(B + '/customer/joint');
  await p.waitForSelector('text=고성능 창호 공동교체');
  const prog1 = await p.getByText(/^3 \/ \d+동$/).textContent(); ok(!!prog1, 'cluster shows 3 joined: ' + prog1);
  await p.waitForSelector('.leaflet-container');
  ok((await p.$$('.leaflet-container')).length >= 2, 'maps rendered');
  const count1 = await p.textContent('text=조건에 맞는 공동공사 희망 이웃 >> xpath=../p[2]');
  await p.click('[role=switch]:has-text("같은 집 유형")');
  const count2 = await p.textContent('text=조건에 맞는 공동공사 희망 이웃 >> xpath=../p[2]');
  ok(count1 !== count2, `toggle changes neighbor count (${count1.trim()} → ${count2.trim()})`);
  ok(await p.isVisible('text=가정 기반 예상치이며 실제 가격은 입찰로 확정됩니다'), 'assumption disclaimer');
  ok(await p.locator('text=실제 낙찰가').count() >= 1, 'actual-awarded basis used for trades with data');
  await p.screenshot({ path: `${SP}/shots/m4-01-joint.png`, fullPage: true });
  await p.click('text=공동견적 참여하기'); await p.waitForSelector('text=참여 중이에요');
  ok(await p.getByText(/^4 \/ \d+동$/).isVisible(), 'now 4 joined');
  ok(await p.isVisible('text=공고 준비 중'), 'cluster moved to tender preparation');
  const t = sql("select t.status, t.method, t.recommendedMethod, t.recommendationReason, t.priceCap from Tender t join Cluster c on c.id=t.clusterId where c.status='CONFIRMED' and c.trade='WINDOW' and c.sigungu='남구'");
  console.log('   tender:', JSON.stringify(t));
  ok(t.length === 1 && t[0].status === 'DRAFT', 'tender draft created with recommendation');
  ok(sql("select count(*) n from Notification n join User u on u.id=n.userId where u.role='ADMIN'")[0].n >= 1, 'admin notified');
  await p.screenshot({ path: `${SP}/shots/m4-02-joined.png`, fullPage: true });
  ok(errors.length === 0, 'no page errors ' + errors.join('|'));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
