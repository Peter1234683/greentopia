const { chromium } = require('playwright');
require('./patch.js');
const SP = __dirname;
const B = 'http://localhost:3000';
const ok = (c, m) => { if (!c) { console.error('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
(async () => {
  const browser = await chromium.launch();
  const c = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' });
  const p = await c.newPage();
  const errors = []; p.on('pageerror', (e) => errors.push(e.message));
  const shot = (n) => p.screenshot({ path: `${SP}/shots/m3-${n}.png`, fullPage: true });
  await p.goto(B + '/login'); await p.click('text=건물주'); await p.click('button[type=submit]'); await p.waitForURL(B + '/customer');
  await shot('01-home');
  await p.goto(B + '/customer/diagnosis'); await shot('02-hub');
  await p.click('text=간이 진단 받기'); await p.waitForURL(/\/diagnosis\?d=/);
  await p.waitForSelector('.recharts-bar-rectangle');
  const bars = await p.$$eval('.recharts-bar-rectangle', (e) => e.length);
  ok(bars === 6, `chart has 6 bars (5 trades + combined): ${bars}`);
  const grade = await p.textContent('text=간이 등급 >> xpath=..');
  ok(/[A-E]/.test(grade), `grade shown: ${grade.trim()}`);
  ok(await p.isVisible('text=평균보다'), 'peer comparison shown');
  ok(await p.isVisible('text=정밀 진단을 추천해요'), 'precise diagnosis recommended (32-year-old 5-household house)');
  ok(await p.isVisible('text=우리 집에 필요한 공사(창호·보일러)를 함께 하면'), 'combined savings for demand trades');
  await p.hover('.recharts-bar-rectangle >> nth=0'); await p.waitForTimeout(300);
  ok(await p.isVisible('text=냉난방 에너지') , 'tooltip on hover');
  await shot('03-result');
  await p.click('text=표로 보기'); ok(await p.isVisible('table'), 'table view');

  await p.click('text=결과 입력하기'); await p.waitForURL(/grai$/);
  await shot('04-grai');
  await p.fill('input[name=baselineKwh]', '60000'); await p.fill('input[name=WINDOW]', '70000');
  await p.click('text=결과 저장하기'); await p.waitForSelector('text=개선 후 값이 현재 상태보다 클 수 없어요');
  ok(await p.inputValue('input[name=baselineKwh]') === '60000', 'grai error keeps values');
  await p.fill('input[name=WINDOW]', '51000'); await p.fill('input[name=COMBINED]', '39000');
  await p.click('text=결과 저장하기'); await p.waitForURL(/\/diagnosis\?d=/);
  ok(await p.isVisible('text=GR-AI 결과 입력'), 'GR-AI result page');
  ok(await p.isVisible('text=지난 진단'), 'history listed');
  ok(await p.isVisible('text=35% 절감 예상'), 'combined 35% from user values');
  await shot('05-grai-result');

  await p.goto(B + '/customer/learn?topic=window'); await p.waitForTimeout(500);
  ok(await p.getAttribute('[role=tab][aria-selected=true]', 'aria-label') === '창호 교체', 'deep link opens window card');
  await p.click('text=다음 ›'); await p.waitForTimeout(800);
  ok(await p.getAttribute('[role=tab][aria-selected=true]', 'aria-label') === '단열 보강', 'next card');
  await p.screenshot({ path: `${SP}/shots/m3-06-learn.png` });
  await p.goto(B + '/customer/learn?topic=why'); await p.waitForTimeout(500);
  await p.screenshot({ path: `${SP}/shots/m3-07-learn-why.png` });
  ok(await p.isVisible('text=출처 확인 중'), 'needsReview badge shown');
  ok(errors.length === 0, 'no page errors ' + errors.join('|'));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
